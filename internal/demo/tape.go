package demo

import (
	"fmt"
	"strings"
	"time"
)

// Cell size of vhs's xterm.js per px of font size (default font, line
// height 1.0), measured from the tmux client size vhs produced: 160x45
// requested at 14px came out as 146x46 with the naive 0.6/1.2 factors.
const (
	cellWidthPerPx  = 0.6575
	cellHeightPerPx = 1.1739
)

// Pixels is the vhs Width/Height that give the scene's cols x rows: the
// cells plus half a cell of slack, plus padding on both sides.
func (t Terminal) Pixels() (w, h int) {
	cw := cellWidthPerPx * float64(t.FontSize)
	ch := cellHeightPerPx * float64(t.FontSize)
	return int((float64(t.Cols)+0.5)*cw) + 2*t.Padding, int((float64(t.Rows)+0.5)*ch) + 2*t.Padding
}

// TapeOutputs are the files a generated tape writes.
type TapeOutputs struct {
	GIF   string   // "" unless the scene's output is gif
	Shots []string // one per screenshot step
}

// Tape generates the vhs tape for the scene against the manifest's windows.
// base is the output path without extension (demo/out/<scene>). scratchGIF
// is where the recording goes when the scene only wants screenshots (vhs
// always records).
func Tape(s *Scene, m *Manifest, base, scratchGIF string) (string, TapeOutputs, error) {
	var b strings.Builder
	var outs TapeOutputs
	line := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }

	w, h := s.Terminal.Pixels()
	line("# Generated by agentctl-demo from scene %q. Do not edit.", s.Name)
	if s.Output == "gif" {
		outs.GIF = base + ".gif"
		line("Output %s", quoteTape(outs.GIF))
	} else {
		line("Output %s", quoteTape(scratchGIF))
	}
	line(`Set Shell "bash"`)
	line("Set FontSize %d", s.Terminal.FontSize)
	line("Set Width %d", w)
	line("Set Height %d", h)
	line("Set Padding %d", s.Terminal.Padding)
	line("Set Theme %s", quoteTape(s.Terminal.Theme))
	line("Set TypingSpeed 30ms")
	line("Set WaitTimeout 20s")
	line("Set CursorBlink false")

	attached := false
	shot := 0
	for i, st := range s.Steps {
		switch {
		case st.Attach != "":
			place, ok := m.Windows[st.Attach]
			if !ok {
				return "", outs, fmt.Errorf("steps[%d].attach: window %q is not in the manifest (re-run `just demo`)", i, st.Attach)
			}
			line("Hide")
			if !attached {
				// The vhs shell may have inherited a TMUX from the caller;
				// drop it so attach does not refuse to nest.
				line("Type %s", quoteTape("exec env -u TMUX -u TMUX_PANE LANG=en_US.UTF-8 tmux -L "+m.label()+" attach -t '"+place.Target()+"'"))
			} else {
				line("Ctrl+B")
				line(`Type ":"`)
				line("Type %s", quoteTape("switch-client -t '"+place.Target()+"'"))
			}
			line("Enter")
			line("Sleep 2.5s")
			line("Show")
			attached = true
		case st.Prefix != "":
			line("Ctrl+B")
			line("Type %s", quoteTape(st.Prefix))
			line("Sleep 500ms")
		case st.Type != "":
			line("Type %s", quoteTape(st.Type))
		case st.Key != "":
			n := max(st.Repeat, 1)
			if n > 1 {
				line("%s %d", st.Key, n)
			} else {
				line("%s", st.Key)
			}
			line("Sleep 300ms")
		case st.Ctrl != "":
			line("Ctrl+%s", strings.ToUpper(st.Ctrl))
		case st.Sleep != "":
			d, _ := time.ParseDuration(st.Sleep)
			line("Sleep %dms", d.Milliseconds())
		case st.Wait != "":
			line("Wait+Screen /%s/", st.Wait)
		case st.Hide:
			line("Hide")
		case st.Show:
			line("Show")
		case st.IsScreenshot():
			shot++
			path := base
			switch {
			case st.Screenshot != "":
				path += "-" + st.Screenshot
			case shot > 1:
				path += fmt.Sprintf("-%d", shot)
			}
			path += ".png"
			outs.Shots = append(outs.Shots, path)
			line("Screenshot %s", quoteTape(path))
			line("Sleep 500ms") // vhs writes screenshots asynchronously
		}
	}
	return b.String(), outs, nil
}

// quoteTape quotes s for a tape string argument, picking a delimiter that s
// does not contain.
func quoteTape(s string) string {
	for _, q := range []string{`"`, `'`, "`"} {
		if !strings.Contains(s, q) {
			return q + s + q
		}
	}
	return `"` + strings.ReplaceAll(s, `"`, `'`) + `"`
}
